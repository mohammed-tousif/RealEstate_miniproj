"""Markdown reports written by scripts/train_price_model.py from the actual run."""
from __future__ import annotations

from pathlib import Path

import pandas as pd

from app.ml.data_prep import CleaningResult
from app.ml.training import MODEL_LABELS


def inr(v: float) -> str:
    if v >= 1e7:
        return f"₹{v / 1e7:.2f} crore"
    return f"₹{v / 1e5:.2f} lakh"


def pct(v: float) -> str:
    return f"{v * 100:.1f}%"


def _table(rows: list[list[str]], header: list[str]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(lines)


def data_quality_md(c: CleaningResult, detection: pd.DataFrame, source: str) -> str:
    f = c.flagged
    excluded = f[f["action"].str.startswith("excluded")]
    out = [
        "# Data quality report",
        "",
        f"Generated by `scripts/train_price_model.py` from `{source}` (sha256 `{c.dataset_sha256[:12]}…`).",
        "All records in this file are **synthetic demonstration data**, not market data.",
        "",
        "## Summary",
        _table([["Raw rows", str(c.raw_rows)], ["Rows used for training", str(len(c.clean))],
                ["Rows excluded", str(c.raw_rows - len(c.clean))], ["Rows flagged but kept",
                 str(f[~f['action'].str.startswith('excluded')]['source_record_id'].nunique())]],
               ["", "Count"]),
        "",
        "## Rules applied",
        "- Schema and enum validation; rows with invalid values are excluded.",
        "- Areas converted to sq ft (1 acre = 43,560, 1 gunta = 1,089, 1 sq m = 10.7639104).",
        "- Coordinates outside the Karnataka bounding box are treated as missing.",
        "- Listings with status *rejected* or *archived* are excluded (not valid asking prices).",
        "- Near-duplicates (same locality and type, area and price within 2%, coordinates within 100 m) "
        "are grouped; one copy is kept so a re-listing cannot appear in both training and test data.",
        "- Price outliers: log(₹/sq ft) is compared with the median of similar listings (same locality "
        "and type, or same type when fewer than 3). Beyond 1.5 × IQR is flagged and kept; more than 5× "
        "away (typo-like) is excluded from training. Nothing else is removed.",
        "- Consistency: width × length vs stated area (10% tolerance), agricultural classification with "
        "conversion claimed, unknown road access. These are flagged and kept.",
        "",
        "## Excluded rows",
        _table([[r.source_record_id, r.issue, r.action] for r in excluded.itertuples()],
               ["Record", "Issue", "Action"]) if len(excluded) else "None.",
        "",
        "## Flagged and kept",
        _table([[r.source_record_id, r.issue, r.action] for r in f[~f.index.isin(excluded.index)].itertuples()],
               ["Record", "Issue", "Action"]),
        "",
        "## Missing values in the raw file",
        "Blank document and plot-dimension columns are mostly *not applicable* (for example no layout "
        "approval for farmland, no building documents for plots), not missing information.",
        "",
        _table([[col, str(int(r.missing)), pct(r.share)] for col, r in c.missing.iterrows()],
               ["Column", "Blank", "Share"]),
    ]
    if len(detection):
        out += [
            "",
            "## Detector check against the generator's planted problems",
            "The synthetic generator deliberately planted some problems and recorded them in "
            "`injected_anomaly`. That column is never used for cleaning; it is only compared afterwards.",
            "",
            _table([[r.kind, str(r.planted), str(r.detected)] for r in detection.itertuples()],
                   ["Planted problem", "Planted", "Detected"]),
            "",
            "Note: the planted ×3 price outlier is flagged but kept, because a 3× deviation cannot be "
            "told apart from a genuine premium without more information. Other flagged outliers are "
            "ordinary records whose price differs from the local median because of conversion, "
            "layout or road-access status.",
        ]
    return "\n".join(out) + "\n"


def evaluation_md(m: dict, plots_written: bool) -> str:
    best = m["model_name"]
    val = m["validation_metrics"]
    rows = [[MODEL_LABELS[k], inr(v["mae_inr"]), inr(v["rmse_inr"]), f"{v['r2']:.3f}", pct(v["mape"]),
             pct(v["median_ape"])] for k, v in val.items()]
    test_rows = [[MODEL_LABELS[k], str(v["n"]), inr(v["mae_inr"]), inr(v["rmse_inr"]), f"{v['r2']:.3f}",
                  pct(v["mape"]), pct(v["median_ape"])] for k, v in m["test_metrics"].items()]
    iv = m["interval"]
    ho = m["locality_holdout"]["results"]
    out = [
        "# Price model evaluation",
        "",
        f"Model version `{m['model_version']}`, trained {m['trained_at']}, seed {m['seed']}.",
        "",
        f"> {m['caveat']}",
        "",
        f"**Target:** {m['target']}.  ",
        f"**Data:** {m['dataset']['clean_rows']} clean rows from {m['dataset']['raw_rows']} raw "
        f"(`{m['dataset']['file']}`).  ",
        f"**Split:** {m['split']['method']}: train {m['split']['train']}, validation "
        f"{m['split']['validation']}, test {m['split']['test']}. Synthetic data has no real time axis, so "
        "there is no time-based split.  ",
        f"**Selection:** {m['selection']}.",
        "",
        "## Validation set (used to choose the model)",
        _table(rows, ["Model", "MAE", "RMSE", "R²", "MAPE", "Median APE"]),
        "",
        f"Selected: **{MODEL_LABELS[best]}**.",
    ]
    if m["tuning"]:
        out += ["", "Grid search (5-fold group CV on the training split, scored by MAE):", ""]
        for k, t in m["tuning"].items():
            params = ", ".join(f"{p}={v}" for p, v in t["best_params"].items())
            out.append(f"- {MODEL_LABELS[k]}: {t['grid_size']} combinations, best {params} "
                       f"(CV MAE {inr(t['cv_mae_inr'])})")
    if best == "linear_regression":
        out += ["", "Why a linear model can win here: the synthetic generator builds prices by *multiplying* "
                "a locality rate by type, conversion, layout and road factors and a power of area. Taking "
                "logs turns that into a sum, which is exactly what Linear Regression on log(price) fits. "
                "Tree models have to approximate the same structure in steps from only "
                f"{m['split']['train']} training rows. Real prices need not follow this shape, so the ranking "
                "of models could change on genuine data."]
    out += [
        "",
        "## Test set (evaluated once, after selection)",
        _table(test_rows, ["Model", "n", "MAE", "RMSE", "R²", "MAPE", "Median APE"]),
        "",
        "R² is computed on rupee values, so a few large farmland prices dominate it; MAPE and median "
        "APE are easier to read across ₹5 lakh plots and ₹1 crore farms.",
        "",
        "## Indicative range",
        f"{iv['method']} gives a nominal {pct(iv['nominal'])} range of ×{2.718281828 ** iv['log_residual_low']:.2f} "
        f"to ×{2.718281828 ** iv['log_residual_high']:.2f} around the estimate. Measured coverage on the "
        f"{iv['test_n']} test rows: **{pct(iv['measured_test_coverage'])}**. With so few rows this coverage "
        "figure is itself uncertain.",
        "",
        "## Error by property type (test set)",
        _table([[r["property_type"], str(r["n"]), inr(r["mae_inr"]), pct(r["mape"]), pct(r["median_ape"])]
                for r in m["error_by_property_type"]], ["Type", "n", "MAE", "MAPE", "Median APE"]),
        "",
        "## Error by locality (test set)",
        "Most localities have only a handful of test rows, so these numbers are noisy.",
        "",
        _table([[r["locality"], str(r["n"]), inr(r["mae_inr"]), pct(r["mape"])]
                for r in m["error_by_locality"]], ["Locality", "n", "MAE", "MAPE"]),
        "",
        "## Unseen localities",
        f"{m['locality_holdout']['method']}. The model never sees the test localities during training.",
        "",
        _table([[MODEL_LABELS[k], inr(v["mae_inr"]), pct(v["mape"]), pct(v["median_ape"])] for k, v in ho.items()],
               ["Model", "MAE", "MAPE", "Median APE"]),
        "",
        "Errors are much larger for localities absent from training. The model has no information about "
        "an unseen locality beyond its city and distance to the centre, so the API adds a warning when a "
        "locality was not in the training data."
        + (" In this run the simple baseline, which falls back to the median ₹/sq ft of the property type, "
           "was more accurate than the trained model on unseen localities."
           if ho["baseline_locality_type_ppsf"]["mae_inr"] < ho[best]["mae_inr"] else ""),
        "",
        "## Permutation importance (test set)",
        "How much the test MAE rises when one feature's values are shuffled. Global, not per property.",
        "",
        _table([[r["feature"], inr(r["mae_increase_inr"]), inr(r["std_inr"])]
                for r in m["permutation_importance"]], ["Feature", "MAE increase", "Std"]),
    ]
    if plots_written:
        out += ["", "## Plots", "",
                "![Predicted vs actual](plots/predicted_vs_actual.png)", "",
                "![Residuals](plots/residuals.png)", "",
                "![Permutation importance](plots/permutation_importance.png)"]
    else:
        out += ["", "Plots were not generated (matplotlib is not installed)."]
    out += ["", "## Library versions",
            ", ".join(f"{k} {v}" for k, v in m["library_versions"].items())]
    return "\n".join(out) + "\n"


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
